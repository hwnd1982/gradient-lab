/**
 * Пауза прод-поллинга версии стейта (SSE на проде нет; см. App.tsx →
 * useAgentSync и API.md «Прод (Vercel)»).
 *
 * База 30 с: полл-тик = ровно 1 команда Upstash (get lab:s/<id>/ver — микро-
 * ключ версий ~16 байт; слот читается только когда версия свежее, см. вер-тик
 * в API.md), активная вкладка 8 ч тратит ~960 команд. 2026-10-13: база 10 с/
 * потолок 60 с упёрлись в дневную квоту free-тарифа Upstash (10k/день) при
 * нескольких открытых вкладках — расход ужат втрое, агенту PUT доходит в
 * среднем за ~15 с (худший случай 30 с). Неудачный тик (429/502/5xx от квоты
 * Upstash, сеть) удваивает паузу до потолка 150 с; успешный ответ (включая
 * 404 «стейта нет») сбрасывает счётчик — поллинг сам возвращается к базе
 * после сброса квоты.
 */
export const PROD_POLL_BASE_MS = 30_000;
export const PROD_POLL_MAX_MS = 150_000;

/** Задержка следующего тика после `failures` неудач подряд. */
export function pollDelayMs(failures: number): number {
    return Math.min(PROD_POLL_MAX_MS, PROD_POLL_BASE_MS * 2 ** failures);
}
